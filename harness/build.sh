#!/bin/sh
# Build everything, into three directories:
#
#   build/bin     the two libraries and the speak window -- what you use
#   build/check   the verification binaries, among them tvh.exe (the
#                 oracle, which drives the original DLL) and tvh_hook.exe
#                 (the same with the decompiled C patched in over it)
#   build/obj     intermediates; safe to delete at any time
#
# Those two need a copy of the original to *run*, though not to build; they
# are what the byte-exact comparison is made against.  The standalone build
# below needs nothing but this repository.
#
# Uses the x86_64 mingw toolchain in freestanding -m32 mode: no 32-bit
# libc/libgcc is installed, so we link against msvcrt.dll/kernel32.dll import
# libraries generated by dlltool from harness/rt/*.def.
set -e
cd "$(dirname "$0")/.."
# Three directories, so that what came out of a build is not mixed up
# with how it got there:
#   bin    what you would use
#   check  the verification binaries; tools/difftest.py drives these
#   obj    intermediates, one directory per way the sources compile
OUT=build/bin
CHECK=build/check
OBJ=build/obj
GEN=$OBJ/gen
HOOK=$OBJ/hook
RT=$OBJ/rt
mkdir -p "$OUT" "$CHECK" "$GEN" "$HOOK/obj" "$RT"

# Windows locks a DLL while anything has it loaded, and an executable
# while it is running, so a build with the speak window open dies in the
# linker with "cannot open output file".  Say what actually happened.
for f in "$OUT/tvtts.dll" "$OUT/tvtts64.dll" "$OUT/speakwin.exe"; do
  # opening for append writes nothing, but still fails on a locked file
  if [ -e "$f" ] && ! ( true >> "$f" ) 2>/dev/null; then
    echo "Cannot write $f: it is in use, or not writable." >&2
    echo "Close the speak window, or whatever else has it open, and" >&2
    echo "build again.  Nothing has been changed." >&2
    exit 1
  fi
done
CFLAGS="-m32 -std=gnu11 -O2 -g -Wall -Wno-unused-function -D__USE_MINGW_ANSI_STDIO=0 \
  -fno-asynchronous-unwind-tables -fno-stack-protector -fno-builtin-printf -fwrapv -fno-strict-aliasing \
  -Iharness"

for lib in kernel32 msvcrt user32 ole32 advapi32; do
  if [ ! -f "$RT/lib$lib.a" ] || [ "harness/rt/$lib.def" -nt "$RT/lib$lib.a" ]; then
    dlltool -m i386 --as-flags=--32 -k -d "harness/rt/$lib.def" -l "$RT/lib$lib.a"
  fi
done

# RT_MIN is process startup and the bits of libgcc a freestanding -m32 build
# needs; the harness tools add the PE loader and its sandbox on top of it.
RT_MIN=""
RT_TOOL=""
for src in harness/rt/start.c harness/rt/libgcc32.c harness/rt/chkstk.S \
           harness/peload.c harness/sandbox.c harness/coverage.c; do
  obj="$RT/$(basename "$src" | sed 's/\.[cS]$/.o/')"
  gcc $CFLAGS -c "$src" -o "$obj"
  case "$src" in harness/rt/*) RT_MIN="$RT_MIN $obj" ;; esac
  RT_TOOL="$RT_TOOL $obj"
done
RTLIBS="$RT_TOOL"

link() { # link <exe> <extra ld args...>
  exe=$1; shift
  # Fixed base, no relocations: hook code calls/jumps straight to absolute
  # addresses inside the DLL, which must not shift if the exe were rebased.
  ld -m i386pe --subsystem console -e _mainCRTStartup@0 --stack 0x800000 \
    --disable-dynamicbase --disable-reloc-section \
    -o "$exe" "$@" $RTLIBS "$RT/libmsvcrt.a" "$RT/libkernel32.a" "$RT/libuser32.a"
}

# --- oracle -----------------------------------------------------------------
gcc $CFLAGS -c harness/tvh.c -o "$OBJ/tvh.o"
link "$CHECK/tvh.exe" "$OBJ/tvh.o"
echo "built $CHECK/tvh.exe"

# --- hook build ---------------------------------------------------------------
for f in src/*.fields; do
  python tools/gen_struct.py "$f" "$GEN/$(basename "$f" .fields)_struct.h"
done
HOOK_OBJS=""
for src in $(find src -name '*.c' -not -path 'src/port/*' | sort); do
  obj="$HOOK/obj/$(echo "$src" | sed 's|^src/||; s|/|_|g; s|\.c$|.o|')"
  gcc $CFLAGS -DTV_HOOK_BUILD -Isrc -I"$GEN" -c "$src" -o "$obj"
  HOOK_OBJS="$HOOK_OBJS $obj"
done
python tools/gen_hookmap.py src "$HOOK/hooks_gen.c" "$HOOK/defsyms.txt" $HOOK_OBJS
gcc $CFLAGS -c "$HOOK/hooks_gen.c" -o "$HOOK/hooks_gen.o"
gcc $CFLAGS -c harness/hooks.c -o "$HOOK/hooks.o"
gcc $CFLAGS -DTV_HOOK_BUILD -Isrc -I"$GEN" -c harness/unit.c -o "$HOOK/unit.o"
gcc $CFLAGS -DTV_WITH_HOOKS -c harness/tvh.c -o "$HOOK/tvh_hook.o"
link "$CHECK/tvh_hook.exe" @"$HOOK/defsyms.txt" "$HOOK/tvh_hook.o" "$HOOK/hooks.o" \
  "$HOOK/unit.o" "$HOOK/hooks_gen.o" $HOOK_OBJS
echo "built $CHECK/tvh_hook.exe"

# --- Spanish hook build -------------------------------------------------------
# The same trick against CGRM_ES.DLL: every function written in es/ is patched
# over the original and the audio has to come out identical.  Spanish is a
# separate decompilation with its own struct layout, so it gets its own struct
# header, its own hook map and its own executable; nothing is shared with src/
# but tv_common.h.  Skipped when there is no Spanish C yet.
if [ -n "$(find es -name '*.c' 2>/dev/null)" ]; then
  HOOKES=$OBJ/hook_es
  mkdir -p "$HOOKES/obj"
  python tools/gen_struct.py es/engine.fields "$GEN/es_engine_struct.h"
  ES_OBJS=""
  for src in $(find es -name '*.c' | sort); do
    obj="$HOOKES/obj/$(echo "$src" | sed 's|^es/||; s|/|_|g; s|\.c$|.o|')"
    gcc $CFLAGS -DTV_HOOK_BUILD -Ies -Isrc -I"$GEN" -c "$src" -o "$obj"
    ES_OBJS="$ES_OBJS $obj"
  done
  # OpenTV's third sample rate is one set of tables for every engine, and the
  # standalone build gets it from src/; the hook build links no src/ objects, so
  # this is the one it needs.
  gcc $CFLAGS -Isrc -I"$GEN" -c src/syn_hifi.c -o "$HOOKES/obj/syn_hifi.o"
  ES_OBJS="$ES_OBJS $HOOKES/obj/syn_hifi.o"
  python tools/gen_hookmap.py es "$HOOKES/hooks_gen.c" "$HOOKES/defsyms.txt" $ES_OBJS
  gcc $CFLAGS -c "$HOOKES/hooks_gen.c" -o "$HOOKES/hooks_gen.o"
  gcc $CFLAGS -DTV_WITH_HOOKS -c harness/tvh.c -o "$HOOKES/tvh_hook.o"
  gcc $CFLAGS -DTV_HOOK_BUILD -Ies -Isrc -I"$GEN" -c harness/unit_es.c -o "$HOOKES/unit_es.o"
  link "$CHECK/tvh_hook_es.exe" @"$HOOKES/defsyms.txt" "$HOOKES/tvh_hook.o" \
    "$HOOK/hooks.o" "$HOOKES/unit_es.o" "$HOOKES/hooks_gen.o" $ES_OBJS
  echo "built $CHECK/tvh_hook_es.exe"
fi

# --- standalone build ---------------------------------------------------------
# No Centigram binary anywhere in here.  The engine is the C in src/, and the
# constant tables it reads are committed under data/ -- see NOTICE for whose
# work those are.  Set TV_DLL to build from your own copy of the original
# instead; tools/extract_data.py says why the two are interchangeable.
DATA=${TV_DLL:-${TV_DATA:-data/en/engine.tvdata}}
if [ ! -f "$DATA" ]; then
  echo "no $DATA: set TV_DATA or TV_DLL, or run tools/extract_data.py" >&2
  exit 1
fi
PORT=$OBJ/port
mkdir -p "$PORT/obj"
PORT_OBJS=""
for src in $(find src -name '*.c' | sort); do
  obj="$PORT/obj/$(echo "$src" | sed 's|^src/||; s|/|_|g; s|\.c$|.o|')"
  gcc $CFLAGS -Isrc -Iinclude -I"$GEN" -c "$src" -o "$obj"
  PORT_OBJS="$PORT_OBJS $obj"
done
python tools/gen_data.py "$DATA" src "$GEN/tvdata.s" $PORT_OBJS
gcc $CFLAGS -c "$GEN/tvdata.s" -o "$PORT/obj/tvdata.o"
PORT_OBJS="$PORT_OBJS $PORT/obj/tvdata.o"

# --- the Spanish engine, in the same library ----------------------------------
# One library carries every language, and the two decompilations give the same
# names to the same jobs -- both engines have an Engine_Feed, and they are
# different functions on different objects.  So Spanish is compiled with every
# name of its own prefixed es_, from a header tools/gen_rename.py writes out of
# the annotations, and its data is laid out under the same prefix.  src/port/api.c
# is the only file that knows there is more than one engine.
ES_DATA=${TV_DLL_ES:-${TV_DATA_ES:-data/es/engine.tvdata}}
if [ -n "$(find es -name '*.c' 2>/dev/null)" ] && [ -f "$ES_DATA" ]; then
  ESPORT=$OBJ/esport
  mkdir -p "$ESPORT/obj"
  python tools/gen_rename.py es,es_port es_ "$GEN/es_rename.h"
  ES_LIB_OBJS=""
  for src in $(find es es_port -name '*.c' | sort); do
    obj="$ESPORT/obj/$(echo "$src" | sed 's|/|_|g; s|\.c$|.o|')"
    gcc $CFLAGS -Ies -Isrc -Iinclude -I"$GEN" -include "$GEN/es_rename.h" \
      -c "$src" -o "$obj"
    ES_LIB_OBJS="$ES_LIB_OBJS $obj"
  done
  python tools/gen_data.py --prefix es_ "$ES_DATA" es,es_port \
    "$GEN/tvdata_es.s" $ES_LIB_OBJS
  gcc $CFLAGS -c "$GEN/tvdata_es.s" -o "$ESPORT/obj/tvdata_es.o"
  PORT_OBJS="$PORT_OBJS $ES_LIB_OBJS $ESPORT/obj/tvdata_es.o"
else
  echo "no Spanish data at $ES_DATA: the library will carry English only" >&2
fi

RTLIBS="$RT_MIN"
link "$CHECK/tv.exe" $PORT_OBJS
echo "built $CHECK/tv.exe"

# --- library tests ------------------------------------------------------------
# Everything but the CLI front end, plus the test program in its place.
LIB_OBJS=$(echo "$PORT_OBJS" | tr ' ' '
' | grep -v 'port_main\.o$' | tr '
' ' ')
gcc $CFLAGS -Isrc -Iinclude -I"$GEN" -c tests/api_test.c -o "$PORT/obj/api_test.o"
link "$CHECK/api_test.exe" "$PORT/obj/api_test.o" $LIB_OBJS
echo "built $CHECK/api_test.exe"

# --- the shared library -------------------------------------------------------
# Everything the CLI links, minus the CLI, plus a DLL entry point.  Only the
# names in harness/rt/tvtts.def are exported, so the engine's own symbols stay
# private; they are plain cdecl names, which is what ctypes and P/Invoke want.
gcc $CFLAGS -c harness/rt/dllmain.c -o "$PORT/obj/dllmain.o"
ld -m i386pe --shared --subsystem console -e _DllMainCRTStartup@12   --disable-dynamicbase --disable-reloc-section   --out-implib "$OUT/libtvtts.a" -o "$OUT/tvtts.dll"   "$PORT/obj/dllmain.o" $LIB_OBJS   "$RT/libgcc32.o" "$RT/chkstk.o" "$RT/libmsvcrt.a" "$RT/libkernel32.a"   harness/rt/tvtts.def
echo "built $OUT/tvtts.dll"

# The same tests again, this time across the DLL boundary, so the exports and
# the calling convention are exercised rather than assumed.
ld -m i386pe --subsystem console -e _mainCRTStartup@0 --stack 0x800000   --disable-dynamicbase --disable-reloc-section   -o "$CHECK/api_test_dll.exe" "$PORT/obj/api_test.o" $RT_MIN   "$OUT/libtvtts.a" "$RT/libmsvcrt.a" "$RT/libkernel32.a"
echo "built $CHECK/api_test_dll.exe"

# --- the SAPI 5 voice, 32-bit ------------------------------------------------
# A COM in-process server with the engine linked into it rather than beside it:
# a COM DLL is loaded by full path and its own directory is not searched for
# dependents, so one that needed tvtts.dll next to it would load in some hosts
# and not others.  Only the four COM entry points are exported.
gcc $CFLAGS -Isapi5 -Iinclude -c sapi5/tvsapi.c -o "$PORT/obj/tvsapi.o"
ld -m i386pe --shared --subsystem console -e _DllMainCRTStartup@12   --disable-dynamicbase --disable-reloc-section --enable-stdcall-fixup   -o "$OUT/tvsapi.dll"   "$PORT/obj/tvsapi.o" "$PORT/obj/dllmain.o" $LIB_OBJS   "$RT/libgcc32.o" "$RT/chkstk.o" "$RT/libmsvcrt.a" "$RT/libkernel32.a"   "$RT/libole32.a" "$RT/libadvapi32.a"   sapi5/tvsapi.def
echo "built $OUT/tvsapi.dll"

# The same server test as at 64 bits, built freestanding against the same
# import libraries.  32 bits is where a COM vtable can go wrong on its own --
# __stdcall decoration, and the export names regsvr32 looks for -- so it is
# worth running here rather than assuming the 64-bit pass covers it.
gcc $CFLAGS -Isapi5 -c sapi5/sapi_test.c -o "$PORT/obj/sapi_test.o"
ld -m i386pe --subsystem console -e _mainCRTStartup@0 --stack 0x800000   --disable-dynamicbase --disable-reloc-section   -o "$CHECK/sapi_test32.exe" "$PORT/obj/sapi_test.o" $RT_MIN   "$RT/libmsvcrt.a" "$RT/libkernel32.a" "$RT/libole32.a" "$RT/libadvapi32.a"
echo "built $CHECK/sapi_test32.exe"

# --- 64-bit ---------------------------------------------------------------
# The first 64-bit TruVoice.  Nothing freestanding here: at 64 bits a normal
# hosted toolchain is available, so this is an ordinary gcc build against the
# system C runtime.  The data comes out of the image with eight-byte pointers
# (tools/gen_data.py --bits 64).
P64=$OBJ/port64
mkdir -p "$P64/obj"
CF64="-m64 -std=gnu11 -O2 -g -Wall -Wno-unused-function -fwrapv \
  -fno-strict-aliasing -Isrc -Iinclude -I$GEN"
OBJ64=""
for src in $(find src -name '*.c' | sort); do
  obj="$P64/obj/$(echo "$src" | sed 's|^src/||; s|/|_|g; s|\.c$|.o|')"
  gcc $CF64 -c "$src" -o "$obj"
  OBJ64="$OBJ64 $obj"
done
python tools/gen_data.py "$DATA" src "$GEN/tvdata64.s" $OBJ64
gcc -m64 -c "$GEN/tvdata64.s" -o "$P64/obj/tvdata.o"
OBJ64="$OBJ64 $P64/obj/tvdata.o"

# Spanish, the same way as at 32 bits: every name of its own prefixed, and its
# data laid out under the prefix.  A stored address is four bytes at either word
# width -- that is what tv_ref is for -- so nothing about the data changes here.
if [ -n "$(find es -name '*.c' 2>/dev/null)" ] && [ -f "$ES_DATA" ]; then
  ES64=""
  for src in $(find es es_port -name '*.c' | sort); do
    obj="$P64/obj/$(echo "$src" | sed 's|/|_|g; s|\.c$|.o|')"
    gcc $CF64 -Ies -include "$GEN/es_rename.h" -c "$src" -o "$obj"
    ES64="$ES64 $obj"
  done
  python tools/gen_data.py --prefix es_ "$ES_DATA" es,es_port \
    "$GEN/tvdata64_es.s" $ES64
  gcc -m64 -c "$GEN/tvdata64_es.s" -o "$P64/obj/tvdata_es.o"
  OBJ64="$OBJ64 $ES64 $P64/obj/tvdata_es.o"
fi

gcc -m64 -o "$CHECK/tv64.exe" $OBJ64
echo "built $CHECK/tv64.exe"

LIB64=$(echo "$OBJ64" | tr ' ' '\n' | grep -v 'port_main\.o$' | tr '\n' ' ')
gcc $CF64 -c tests/api_test.c -o "$P64/obj/api_test.o"
gcc -m64 -o "$CHECK/api_test64.exe" "$P64/obj/api_test.o" $LIB64
echo "built $CHECK/api_test64.exe"

# --- the filter-state diagnostic ---------------------------------------------
# Built with TV_DIAG, which is the only thing that compiles the counters in, so
# nothing above is affected.  It says how hard a voice drives the filter bank
# and whether any state leaves 16 bits -- which is how a custom voice is told
# apart from a broken one.  See docs/VOICES.md.
VD=$OBJ/voicediag
mkdir -p "$VD"
VD_OBJS=""
for src in src/engine/generate.c src/engine/frame.c tools/voicediag.c; do
  obj="$VD/$(basename "$src" .c).o"
  gcc $CF64 -DTV_DIAG -c "$src" -o "$obj"
  VD_OBJS="$VD_OBJS $obj"
done
VD_REST=$(echo "$LIB64" | tr ' ' '
' |   grep -vE 'engine_generate\.o$|engine_frame\.o$' | tr '
' ' ')
gcc -m64 -o "$CHECK/voicediag.exe" $VD_OBJS $VD_REST
echo "built $CHECK/voicediag.exe"

gcc -m64 -shared -o "$OUT/tvtts64.dll" $LIB64 \
  -Wl,--out-implib,"$OUT/libtvtts64.a" harness/rt/tvtts.def
echo "built $OUT/tvtts64.dll"

# --- the SAPI 5 voice, 64-bit, and the test that drives it ------------------
# 64-bit SAPI applications need a 64-bit voice and 32-bit ones a 32-bit voice,
# so both are built; each registers tokens naming a server of its own width.
gcc $CF64 -Isapi5 -c sapi5/tvsapi.c -o "$P64/obj/tvsapi.o"
gcc -m64 -shared -o "$OUT/tvsapi64.dll" "$P64/obj/tvsapi.o" $LIB64   sapi5/tvsapi.def -lole32 -ladvapi32
echo "built $OUT/tvsapi64.dll"

# The server driven through its own DllGetClassObject, with a site and a token
# of the test's own -- so it needs no registry entries and no administrator.
gcc -m64 -std=gnu11 -O2 -Wall -Wextra -Isapi5 -o "$CHECK/sapi_test.exe"   sapi5/sapi_test.c -lole32 -luuid -ladvapi32
echo "built $CHECK/sapi_test.exe"

# --- the speak window ---------------------------------------------------------
# A Win32 GUI over the library: type text, pick a voice, hear it, save a WAV.
# Built 64-bit against tvtts64.dll with an ordinary hosted toolchain -- none of
# the freestanding -m32 machinery above applies to it.  The import library is
# named by path rather than with -L, which is shorter than telling the
# linker a directory and then a name that is only in it.
gcc -m64 -O2 -Wall -Wextra -municode -mwindows -o "$OUT/speakwin.exe" \
  gui/speakwin.c -Iinclude "$OUT/libtvtts64.a" \
  -lcomctl32 -lwinmm -lcomdlg32 -lgdi32
echo "built $OUT/speakwin.exe"

# --- packages, if any have already been built --------------------------------
# The engine reaches people through packages -- the NVDA add-on, the SAPI 5
# installer -- and each takes a *copy* of it at packaging time.  A package
# sitting next to a freshly built DLL and carrying the previous one is worse
# than no package at all: it looks current, installs cleanly, and quietly
# speaks with the old engine.  That is exactly how the Spanish contour fix
# came to be untestable on 2026-09-29.
#
# Packaging itself stays opt-in -- someone who has never built one sees nothing
# here -- but anything already built is rebuilt with everything else, so it can
# never fall behind the engine.  A new platform target belongs in this block
# too, on the same terms.
had64=0
had32=0
for a in "$OUT"/*.nvda-addon; do
  [ -e "$a" ] || continue
  case "$a" in
    *-x86.nvda-addon) had32=1 ;;
    *) had64=1 ;;
  esac
done
if [ "$had64" = 1 ] || [ "$had32" = 1 ]; then
  rm -f "$OUT"/*.nvda-addon
  if [ "$had64" = 1 ]; then
    python tools/make_addon.py >/dev/null && echo "repackaged the 64-bit NVDA add-on"
  fi
  if [ "$had32" = 1 ]; then
    python tools/make_addon.py --32 >/dev/null && echo "repackaged the 32-bit NVDA add-on"
  fi
fi

# The SAPI 5 installer carries both tvsapi DLLs, and those have the engine
# linked into them, so it goes stale the same way.  NSIS is not part of the
# toolchain this project otherwise needs, so it is looked for rather than
# assumed; without it the stale installer is removed instead, because leaving
# one that looks current is the failure being prevented.
SETUP="$OUT/OpenTV-SAPI5-Setup.exe"
if [ -e "$SETUP" ]; then
  NSIS=""
  if command -v makensis >/dev/null 2>&1; then
    NSIS=makensis
  else
    for c in "/c/Program Files (x86)/NSIS/makensis.exe" \
             "/c/Program Files/NSIS/makensis.exe"; do
      if [ -x "$c" ]; then NSIS=$c; break; fi
    done
  fi
  if [ -n "$NSIS" ]; then
    if "$NSIS" sapi5/installer.nsi >/dev/null 2>&1; then
      echo "rebuilt $SETUP"
    else
      rm -f "$SETUP"
      echo "warning: makensis failed; removed the stale SAPI 5 installer" >&2
    fi
  else
    rm -f "$SETUP"
    echo "warning: NSIS not found, so the SAPI 5 installer was stale and has" >&2
    echo "         been removed.  Rebuild it with:" >&2
    echo "           makensis sapi5/installer.nsi" >&2
  fi
fi

# The build prints a line per target as it goes, which is a lot to read
# back.  This is the part worth reading: what exists now and where.
echo
echo "Ready to use, in $OUT:"
for f in tvtts.dll tvtts64.dll tvsapi.dll tvsapi64.dll speakwin.exe; do
  [ -f "$OUT/$f" ] && echo "    $f"
done
echo "  link against it with $OUT/libtvtts.a or $OUT/libtvtts64.a"
echo "  the NVDA add-on is a separate step: python tools/make_addon.py"
echo "    (one already packaged is rebuilt here, so it cannot go stale)"
echo "  the SAPI 5 installer likewise: makensis sapi5/installer.nsi"
echo "  the SAPI voices are registered by the installer, or by hand:"
echo "    regsvr32 $OUT/tvsapi64.dll   (64-bit applications)"
echo "    regsvr32 $OUT/tvsapi.dll     (32-bit, needs the 32-bit regsvr32)"
echo
echo "Verification binaries, in $CHECK: $(ls "$CHECK" | tr '\n' ' ')"
echo "  run them with python tools/difftest.py"
echo
echo "Intermediates are under $OBJ and can be deleted at any time."
