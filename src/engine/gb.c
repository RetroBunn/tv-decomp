/*
 * General British: the American engine's vowels, moved.
 *
 * The text analysis, the lexicon, the letter-to-sound rules, the stress rules,
 * the prosody and every consonant are wanted exactly as they are -- GB and GA
 * are the same language -- so this is not a front end.  It is a shift applied
 * to where stage 3 aims each vowel's formants.
 *
 * WHERE IT HAS TO GO, which is not where it first looked.  Stage 3 starts a
 * phoneme at g_pt_f1..f3[class], and it would be tidy to move those.  It does
 * not work: the rules that run afterwards -- Stage3_Rules, Stage3_Formants,
 * Stage3_GlideTab and the rest -- overwrite the formant targets for a vowel
 * outright, from context tables keyed by the neighbouring phonemes.  Moving
 * the base table changes nothing by the time a frame is written, and that was
 * measured rather than assumed: with the base table moved, NURSE still came
 * out of stage 3 at F1 384, F2 1436, F3 1808 in both accents.
 *
 * So the shift is applied at the END of Stage3_Phone, after every rule has
 * had its say and immediately before the targets are laid into the tracks.
 * That is also the better model of what an accent is: coarticulation, the
 * consonant transitions and the allophonic rules all belong to the language
 * and are kept, and only the vowel's home position moves.
 *
 * The amount it moves by is the difference between Cruttenden's measured GB
 * value and Centigram's American one, per vowel, generated into gb_vowels.h
 * by tools/gen_gb_vowels.py.  That file records which of his three tables
 * each row comes from, how many speakers were behind it and in what speaking
 * condition.  See lang/eng/research/gimson8.md.
 *
 * F3 AND NON-RHOTICITY.  Cruttenden publishes F1 and F2 only, so every GB F3
 * in that table is the engine's own value, carried across unchanged -- which
 * makes F3 a no-op for fifteen of the twenty-one vowels.  The exceptions are
 * the six American renders r-coloured, by collapsing F3 to 1450-1730 Hz
 * where a plain vowel sits above 2100.  GB has no r-coloured vowel at all,
 * so those six are given the F3 of a vowel of similar quality that never
 * carried the colouring, and they then go through exactly the same remap as
 * F1 and F2.
 *
 * A FLOOR on F3 was the first way of doing this -- leave it alone unless it
 * falls into the r-coloured region -- and it worked, but it needed a
 * threshold of 2000 Hz that is nobody's measurement, and a clamp steps:
 * NURSE's F3 jumped 720 Hz in one frame where the floor caught it.  The
 * remap needs no threshold, because the only vowels whose GB F3 differs from
 * their American F3 are the six, and it is continuous.  Nothing in this file
 * now knows which vowels are r-coloured, or what r-colouring is.
 *
 * With GB off nothing below runs, so the corpus is untouched.
 */
#include "engine.h"

/* @0x100eece8 */ extern const uint8_t g_pt_f1[64];
/* @0x100eed28 */ extern const uint8_t g_pt_f2[64];
/* @0x100eed68 */ extern const uint8_t g_pt_f3[64];
/* @0x100eefd8 */ extern const uint8_t g_at_f1[];
/* @0x100eeff0 */ extern const uint8_t g_at_f2[];
/* @0x100ef008 */ extern const uint8_t g_at_f3[];

/* One vowel, as tools/gen_gb_vowels.py writes it: the phoneme it is spelt
 * with, the class stage 3 indexes by, its GB target and the target it glides
 * to, both stored the way the engine's own tables store them. */
typedef struct {
    char    sym;
    uint8_t cls;
    uint8_t pt[3];              /* F1, F2, F3 */
    uint8_t at[3];              /* the same, where the vowel glides to */
} tv_gb_vowel;

#include "gb_vowels.h"

#define TV_GB_VOWELS ((int)(sizeof g_gb_vowel / sizeof g_gb_vowel[0]))

/*
 * And the words where GB and American pick a DIFFERENT vowel, which no amount
 * of re-aiming can reach: *bath* is /a/ in America and /A:/ in Britain, and
 * the engine's own analysis has already chosen /a/ by the time the formants
 * are set.  Those are a lexicon, generated by tools/gen_gb_lexicon.py from
 * Cruttenden's own word lists -- BATH (8.9.7), PALM, CLOTH (8.9.8) and yod
 * coalescence (7.10.1) -- by running each word through the American engine
 * and substituting one vowel, so stress and every consonant stay as the
 * letter-to-sound rules produced them.
 *
 * It is a list and not a rule because the environment Cruttenden gives for
 * BATH also catches *gas, mass, ant, hand, random* and *ample*, which keep
 * /a/ in GB -- and because *ant* and *aunt* come out of the American engine
 * as the same string, so nothing downstream could ever tell them apart.
 */
typedef struct {
    const char *word;           /* upper case, as stage 1 builds it */
    const char *from;           /* the phonemes American produces */
    const char *to;             /* what General British wants instead */
} tv_gb_sub_entry;

#include "gb_lexicon.h"

#define TV_GB_LEX ((int)(sizeof g_gb_lex / sizeof g_gb_lex[0]))

/*
 * Whether the engine is speaking GB at the moment.  Process-wide, like the
 * extension mask and the user lexicon, and set by the language layer around a
 * call; a tvtts_synth is documented as not thread safe.
 */
static int g_gb_on;

/*
 * Diagnostic: which frames a vowel wrote, and which vowel.
 *
 * NULL in the shipped library, never called, and the only cost is one test
 * per phoneme.  tools/gb_formants.c sets it so a dump can be read by vowel
 * instead of guessed at from the shape of the numbers -- which is what
 * comparing one set of targets against another needs.  Hooking the engine's
 * own Stage3_Emit was tried first and cannot work: --wrap only redirects
 * references resolved between object files, and stage3.c calls its own
 * Stage3_Emit directly.
 */
void (*tv_gb_frame_trace)(int32_t from, int32_t to, char sym);

void tv_gb_set(int on)
{
    g_gb_on = (on != 0);
}

int tv_gb_get(void)
{
    return g_gb_on;
}

/*
 * class -> row, or NULL for every class GB leaves alone: the consonants, the
 * stops and the silences, which are two thirds of the table.
 */
static const tv_gb_vowel *gb_row(int cls)
{
    static signed char idx[64];
    static int built;

    if (!built) {
        int i;

        for (i = 0; i < 64; i++)
            idx[i] = -1;
        for (i = 0; i < TV_GB_VOWELS; i++)
            if (g_gb_vowel[i].cls < 64)
                idx[g_gb_vowel[i].cls] = (signed char)i;
        built = 1;
    }
    if ((unsigned)cls >= 64 || idx[cls] < 0)
        return NULL;
    return &g_gb_vowel[idx[cls]];
}

/*
 * Put x, which sits somewhere on the American line from us0 to us1, at the
 * matching place on the General British line from gb0 to gb1.
 *
 * This is the whole mechanism, and the reason it is a remap and not a shift.
 * A vowel in this engine is not one target but two -- where it starts
 * (g_pt_*) and where it glides to (g_at_*) -- and ADDING a constant to every
 * frame moves both ends by the same amount, so the vowel keeps its American
 * SHAPE and merely sits somewhere else.  For the six vowels American spells
 * with an <r> that is precisely wrong: their shape *is* the /r/.  Measured,
 * with the constant shift in place: *far* still ran F2 from 1076 up to 1452,
 * *four* from 812 to 1316, *fair* down from 1772 to 1604 -- the r-gesture
 * intact, only its F3 colouring removed.  General British wants all three
 * steady, at 1155, 828 and 1864.
 *
 * Remapping the two ends independently makes them steady for free: GB's
 * glide target for those vowels *is* its primary, so the American line
 * collapses onto a single GB value and the glide stops existing.  No rule
 * says "flatten", and nothing here knows which vowels are r-coloured.
 *
 * It also lands on the value instead of near it.  A constant shift adds
 * Cruttenden's difference to whatever the context rules produced, so it
 * inherits their displacement twice over and overshoots; the endpoints here
 * are absolute.  What survives is everything that is not the target: the
 * approach from the preceding consonant, the release into the next, and any
 * undershoot, which keeps its distance rather than being dragged onto a
 * value the engine never reached.  That is the part that belongs to the
 * language rather than the accent.
 *
 * BEYOND the two ends it extends the same line, so the mapping is one
 * continuous function of the value and the vowel can never acquire a step
 * that the American did not have.  Driving the outside case from the frame's
 * POSITION in the phoneme instead was tried, to stop MOUTH's opening frame
 * -- which sits below the glide target because it is still climbing out of
 * the /n/ -- being read as having overshot a glide it had not begun.  It
 * trades the fault for a worse one: position and value disagree where they
 * meet, and *now* gained a 136 Hz step in the MIDDLE of the vowel, which the
 * seam at a consonant boundary is not.  The engine's own vowel onsets move
 * as much as 204 Hz in one frame (*that bad man*), so a seam there is within
 * what it already does; a break in the middle of a vowel is not.
 */
static int32_t gb_remap(int32_t x, int32_t us0, int32_t us1,
                        int32_t gb0, int32_t gb1)
{
    int32_t num = x - us0, den = us1 - us0, v;

    if (den == 0)
        return x + (gb0 - us0);         /* steady in American: a shift */
    if (den < 0) {
        num = -num;
        den = -den;
    }
    if (num <= 0)
        return x + (gb0 - us0);         /* short of the vowel's own start */
    if (num >= den)
        return x + (gb1 - us1);         /* past where it was heading */
    v = num * (gb1 - gb0);
    v = (v >= 0) ? (v + (den >> 1)) / den : -((-v + (den >> 1)) / den);
    return gb0 + v;
}

/*
 * How many frames before `from` the preceding phoneme is already sitting at
 * this one's opening value.
 *
 * Stage 3 lays a vowel's opening value into the closing frames of the
 * phoneme in front of it, so the track arrives smoothly rather than jumping.
 * Those frames belong to the consonant and are not ours to re-aim, but
 * leaving them American puts a step at the seam: *far* jumped 240 Hz in a
 * single 10 ms frame, and the constant shift did the same.  Mapping them
 * along with the vowel closes it, because the remap is a function of the
 * value alone and so gives them the same answer.
 *
 * Counted per track, not once for all three: across the lead-in F2 is held
 * flat at the vowel's target while F1 is still ramping, so asking for both
 * to match stopped the walk after two frames and merely moved the step.
 * Bounded at eight, since a longer identical run is a coincidence rather
 * than a lead-in.
 */
static int32_t gb_lead(const uint8_t *t, int32_t from, int32_t n)
{
    int32_t o = t[from & 255], lead, i;

    for (lead = 0; lead < 8 && from - lead - 1 >= 0; lead++) {
        i = (from - lead - 1) & 255;
        if (t[i] != o)
            break;
    }
    return (n + lead > 256) ? 0 : lead;
}

/*
 * Remap one track across a phoneme's frames and its lead-in.
 *
 * A vowel the engine holds steady has no line to remap along, so there is
 * nothing to do but shift it -- and a shift arrives whole on the first
 * frame, which is a seam of its full size: NURSE's F3 moved 896 Hz and so
 * stepped by that much in one frame.  Those get eased in over three frames.
 * This is position-driven, but unlike the attempt above there is no
 * value-driven branch for it to disagree with -- a steady vowel has only the
 * one case -- so it cannot break the vowel's interior.
 */
static void gb_apply(uint8_t *t, int32_t from, int32_t n,
                     int32_t us0, int32_t us1, int32_t gb0, int32_t gb1)
{
    int32_t lead = gb_lead(t, from, n), ramp, i, k, v, w;

    ramp = (us0 == us1 && gb0 != us0) ? 3 : 0;
    if (ramp > n)
        ramp = n;
    for (k = -lead; k < n; k++) {
        i = (from + k) & 255;
        v = gb_remap((int32_t)t[i], us0, us1, gb0, gb1);
        if (k < ramp) {
            w = (k < 0) ? 0 : k + 1;
            v = (int32_t)t[i] + (v - (int32_t)t[i]) * w / (ramp + 1);
        }
        t[i] = (uint8_t)((v < 0) ? 0 : (v > 255) ? 255 : v);
    }
}

/*
 * Move one vowel's formants from American to General British, in the TRACKS.
 *
 * Not in stage 3's targets, which is where this started and where it does
 * almost nothing.  Measured: for *nurse*, shifting s3_param[9..11] changed
 * six frames of the approach and left all nineteen frames of the vowel body
 * untouched, because an r-coloured vowel's body is drawn by the glide tables
 * (Stage3_Formants, Stage3_GlideTab) straight into the track buffer and never
 * passes through those targets at all.  F2 moved by exactly 0 Hz.
 *
 * So it is applied here instead, to the frames this phoneme actually wrote,
 * after every path has had its say.  `from` and `to` are the track ring
 * positions before and after the phoneme; the ring is 256 frames and wraps,
 * hence the masking.
 *
 * Units are the track's own, not Hz: F1 is the byte times 4, F2 the byte
 * times 8 plus 500, F3 the byte times 16 (src/engine/stage3.c).  Both tables
 * are read in those units, so no conversion happens here at all.
 */
void tv_gb_track_shift(uint8_t *f1, uint8_t *f2, uint8_t *f3,
                       int32_t from, int32_t to, int cls)
{
    const tv_gb_vowel *r;
    int32_t a1, b1, a2, b2, a3, b3, n;

    if (!g_gb_on)
        return;
    r = gb_row(cls);
    if (r == NULL)
        return;

    /*
     * The American line, both ends.  Only the classes below 0x13 have a
     * glide target; the rest are steady, and for those the two ends are the
     * same value and the remap degenerates to the shift it used to be.
     */
    a1 = (int32_t)g_pt_f1[cls];
    a2 = (int32_t)g_pt_f2[cls];
    b1 = (cls < 0x13) ? (int32_t)g_at_f1[cls] : a1;
    b2 = (cls < 0x13) ? (int32_t)g_at_f2[cls] : a2;

    a3 = (int32_t)g_pt_f3[cls];
    b3 = (cls < 0x13) ? (int32_t)g_at_f3[cls] : a3;

    /*
     * Count the frames rather than compare positions.  The write cursor is a
     * running total that is only masked when it indexes the ring, so `to` is
     * routinely past 255 and "walk until i == to" never terminates -- which
     * it duly did not.
     */
    n = to - from;
    if (n <= 0 || n > 256)
        return;

    gb_apply(f1, from, n, a1, b1, r->pt[0], r->at[0]);
    gb_apply(f2, from, n, a2, b2, r->pt[1], r->at[1]);
    gb_apply(f3, from, n, a3, b3, r->pt[2], r->at[2]);

    if (tv_gb_frame_trace != NULL)
        tv_gb_frame_trace(from, from + n, r->sym);
}

/*
 * NON-RHOTICITY AND THE /r/ LINKS, which are one rule and not two: /r/
 * survives only before a vowel.  The silent /r/ of *card*, the linking /r/
 * of *far off*, the intrusive /r/ of *vanilla essence* and the refusal to
 * intrude in *straw in the wind* all fall out of that single statement plus
 * the question of where American put an /r/ in the first place.
 *
 * Almost none of it is here, and that was the finding that shrank the job.
 * The American engine already folds a post-vocalic /r/ into the vowel in
 * front of it and then drops the consonant, in src/engine/vowel.c, so a
 * finished American string carries no post-vocalic `R` at all -- *card* is
 * `Kr1Dp`, *bird* `B31Dp`, *four* `Fg1`.  The vowel it folds to is the one
 * General British uses for that same lexical set, so those words want
 * nothing from us at all; GB differs only in declining the deletion when a
 * vowel follows.  A whole fold table was written here first, from word pairs
 * the engine spells both ways (*card* `KoRD` against *start* `StrT`), before
 * measuring the FINISHED string showed the engine had the same table and a
 * better one.  It was deleted.
 *
 * What is left here are the two questions stage 1 cannot answer on its own.
 *
 * Is this one of the vowels American renders r-coloured -- that is, does the
 * American engine say there was ever an /r/ here?
 *
 * This is the whole of Cruttenden's historical-/r/ condition, and it costs
 * no spelling lookup, because A RHOTIC ACCENT IS ITSELF THE RECORD of which
 * /r/s are historical: American pronounces those and only those.  Measured,
 * and the separation is exact where it matters most -- *floor* *store* *for*
 * *nor* end on `g`, American's r-coloured THOUGHT, while *law* *saw* *straw*
 * *thaw* *jaw* *draw* *raw* *claw* end on plain `w`; *far* ends on `r` while
 * *spa* *bra* *ma* *pa* *schwa* end on `o`.
 *
 * So §12.4.7's case (d), the intrusive /r/ after /A:/ and /O:/ that the book
 * reports speakers avoiding, is refused by this test and needs no list.
 */
int tv_gb_r_colored(uint8_t v)
{
    return v == 'r' || v == 'k' || v == '3' || v == '4' || v == 'c' ||
           v == 'g';
}

/*
 * The vowels an /r/ link may be added to: §12.4.7(1) names /E: A: O:/ and
 * the ones that may end in schwa, /@ 3: I@ U@/, which is the r-coloured set
 * plus schwa itself.
 *
 * Schwa is in it with no historical test, and that is case (c) -- *vanilla
 * essence*, *vodka and tonic* -- which the book reports as normal usage and
 * groups with the links rather than with the intrusions speakers avoid.
 */
int tv_gb_r_link(uint8_t v)
{
    return tv_gb_r_colored(v) || v == '@';
}

/*
 * Words with a SINGLE <r> that still take a short vowel.
 *
 * §8.9.4's "Spellings of /E:/" table settles the doubled-<rr> rule from the
 * book's own data: across its four spelling rows (`ar, are`, `air`, `ear`,
 * `ae`) it gives twenty-nine example words, *care* and *parent* among them,
 * and not one doubles the <r>.  So a doubled <rr> never takes /E:/, which is
 * what stage 1 keys on; the whole list is checked in the notes rather than
 * copied out here.
 *
 * A single <r> is the ambiguous case, and this is the short-vowel side of
 * it.  OURS, not the book's: these are not in its /E:/ lists, but those are
 * examples rather than an inventory, so absence is weak evidence and each
 * word here is a judgement.  Only words measured to come out wrong are
 * listed, and *very* is the reason the list exists at all -- far too
 * common a word to leave as /vE:rI/.
 *
 * Each row states its vowel rather than leaving stage 1 to read it off the
 * spelling, because the spelling does not always say: *laurel* is /Q/ while
 * *Laura* and *aural* are /O:/, so <aur> settles nothing.
 *
 * The /Q/ rows are the single-<r> half of §7.12.1's *orange* class, where
 * GA has /O:/ or /A:/ and GB has /Q/, so the engine gives START, NORTH or
 * THOUGHT.  *sorry* is in §8.9.8's own /Q/ spelling table and *borrow* in
 * its prose.  Inflections are not covered.
 */
typedef struct {
    const char *word;
    char vowel;                 /* what General British wants there */
} tv_gb_short;

static const tv_gb_short g_gb_short_r[] = {
    { "AMERICA",   'e' },
    { "AMERICAN",  'e' },
    { "BARON",     'a' },
    { "CAROL",     'a' },
    { "CHARACTER", 'a' },
    { "CORAL",     'o' },
    { "FLORIST",   'o' },
    { "FOREST",    'o' },
    /* *laurel* is in §8.9.8's /Q/ list and WAS in the CLOTH lexicon, but
     * that substitution could never survive: `o` in front of an `R` folds
     * straight back to START.  It needs the syllable marker, so it belongs
     * here instead and has been taken out of the generator's CLOTH list. */
    { "LAUREL",    'o' },
    { "MERIT",     'e' },
    { "MORAL",     'o' },
    { "ORANGE",    'o' },
    { "ORIGIN",    'o' },
    { "PARIS",     'a' },
    { "PARISH",    'a' },
    { "PERIL",     'e' },
    { "VERY",      'e' },
    /* <orr> after /w/ is STRUT, not the LOT the spelling rule would hand
     * it: *worry* is /'wVrI/, where the engine gives NURSE. */
    { "WORRY",     'v' }
};

char tv_gb_short_r(const char *word)
{
    int i, n = (int)(sizeof g_gb_short_r / sizeof g_gb_short_r[0]);

    for (i = 0; i < n; i++) {
        const char *a = word, *b = g_gb_short_r[i].word;

        while (*a != 0 && *a == *b) {
            a++;
            b++;
        }
        if (*a == 0 && *b == 0)
            return g_gb_short_r[i].vowel;
    }
    return 0;
}

/*
 * The CLOTH words whose word class General British has to promote.
 *
 * American spells *off* `%w1F` where the word is prominent -- *the light is
 * off* -- and `%wF` where it is not, *take it off now*.  The CLOTH swap to
 * /6/ loses the first of those.  A `%` word carries a mark only when its
 * vowel can take one and /6/ cannot, while a `&` word carries one either
 * way: *cough* is the same swap in a content word and stays `&Ko1F`.
 * Promoting the class hands the mark back without forcing it, since the
 * engine still decides per utterance where an accent goes -- so the uses
 * American leaves bare should stay bare.
 *
 * One word, because one word is what measurement found: of the CLOTH list
 * only *off* is spelt with `%`.
 */
static const char *const g_gb_mark[] = { "OFF" };

int tv_gb_mark(const char *word)
{
    int i, n = (int)(sizeof g_gb_mark / sizeof g_gb_mark[0]);

    for (i = 0; i < n; i++) {
        const char *a = word, *b = g_gb_mark[i];

        while (*a != 0 && *a == *b) {
            a++;
            b++;
        }
        if (*a == 0 && *b == 0)
            return 1;
    }
    return 0;
}

/*
 * What General British does differently to this word's vowel, or NULL.
 *
 * Stage 1 asks this AFTER its own analysis is complete and swaps the few
 * phonemes named, rather than replacing the word -- so the word class, the
 * stress and every context-sensitive allophone the engine chose all survive.
 * The table is sorted, so this is a binary search; `word` arrives upper case
 * and NUL terminated.
 */
const TvGbSub *tv_gb_sub(const char *word)
{
    int lo = 0, hi = TV_GB_LEX - 1;

    if (!g_gb_on || word == NULL || word[0] == 0)
        return NULL;
    while (lo <= hi) {
        int mid = lo + ((hi - lo) >> 1);
        const char *a = word;
        const char *b = g_gb_lex[mid].word;
        int d = 0;

        while (*a != 0 || *b != 0) {
            d = (int)(unsigned char)*a - (int)(unsigned char)*b;
            if (d != 0)
                break;
            a++;
            b++;
        }
        if (d == 0)
            return (const TvGbSub *)&g_gb_lex[mid].from;
        if (d < 0)
            hi = mid - 1;
        else
            lo = mid + 1;
    }
    return NULL;
}
